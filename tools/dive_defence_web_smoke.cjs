const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const path=require('node:path');
const assert=require('node:assert/strict');
const delay=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const server=spawn('python3',['-m','http.server','8772','--bind','127.0.0.1','--directory',path.resolve(__dirname,'../builds/web')],{stdio:'ignore'});
 let browser;let checks=0;const errors=[];
 const check=(v,t)=>{assert.ok(v,t);checks++;console.log('PASS: '+t)};
 try{
  await delay(500);
  browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1280,height:800}});
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  const state=()=>page.evaluate(()=>window.firstSortieState);
  const wait=async (fn,argument=null)=>{try{return await page.waitForFunction(fn,argument,{timeout:120000})}catch(e){console.error('STATE',JSON.stringify(await state()),'ERRORS',errors);await page.screenshot({path:'/tmp/dive-web-failure.png'});throw e}};
  const click=async key=>{const [x,y]=(await state())[key];await page.mouse.click(x,y)};
  const walk=async(target)=>{
   for(let step=0;step<700;step++){
    const s=await state(),p=s.ground_position,dx=target[0]-p[0],dz=target[2]-p[2];
    if(Math.hypot(dx,dz)<1.2){for(const key of ['w','ArrowLeft','ArrowRight'])await page.keyboard.up(key);return;}
    const desired=Math.atan2(-dx,-dz),error=Math.atan2(Math.sin(desired-s.pilot_yaw),Math.cos(desired-s.pilot_yaw));
    for(const key of ['ArrowLeft','ArrowRight'])await page.keyboard.up(key);
    if(Math.abs(error)>.1)await page.keyboard.down(error>0?'ArrowLeft':'ArrowRight');
    if(Math.abs(error)<.35)await page.keyboard.down('w');else await page.keyboard.up('w');
    await delay(150);
   }
   throw Error('Could not reach Bofors '+JSON.stringify(await state()));
  };
  await page.goto('http://127.0.0.1:8772/index.html?smoke=1');
  await wait(()=>window.firstSortieState?.selecting);
  await click('missions_button');await wait(()=>window.firstSortieState.missions_selecting);
  await click('mission_picker');await delay(300);await page.keyboard.press('ArrowUp');await page.keyboard.press('Enter');
  await wait(()=>window.firstSortieState.mission_selected===1);
  check((await state()).missions_selecting,'AA mission can be selected without prematurely launching');
  await click('mission_depart_button');
  await wait(()=>window.firstSortieState.aa_defence?.phase==='WAIT_MOUNT' && window.firstSortieState.aa_count===18);
  check((await state()).aa_defence.spawned===0 && (await state()).aa_defence.player_hp===100,'Luqa ground mission waits with healthy independent operator and no enemies');
  await page.keyboard.down('Control');await delay(1000);await page.keyboard.up('Control');
  check((await state()).aa_shots===0,'All unoccupied guns ignore firing input');
  await page.keyboard.press('e');await wait(()=>window.firstSortieState.ground_mode==='gun');
  check((await state()).ground_reticle && (await state()).aa_mounted===1,'Real browser E mounts one gun with exclusive controls and reticle');
  await wait(()=>window.firstSortieState.aa_mouse.captured && document.pointerLockElement!==null);
  check(await page.evaluate(()=>document.pointerLockElement!==null),'Actual browser pointer lock acquired on E mount');
  const initialAim=(await state()).aa_mouse;
  await page.mouse.move(800,330,{steps:10});
  await wait(previous=>Math.abs(window.firstSortieState.aa_mouse.yaw-previous.yaw)>.04,initialAim);
  check(Math.abs((await state()).aa_mouse.pitch-initialAim.pitch)>.02,'Relative mouse moves both physical gun axes without arrow input');
  await page.mouse.down({button:'right'});await wait(()=>window.firstSortieState.aa_mouse.fov<33);
  check((await state()).aa_mouse.fov<33,'RMB zooms sight in browser');
  await page.mouse.up({button:'right'});await wait(()=>window.firstSortieState.aa_mouse.fov>57);
  await page.keyboard.press('Escape');await wait(()=>window.firstSortieState.aa_mouse.settings && !window.firstSortieState.aa_mouse.captured);
  check(await page.evaluate(()=>document.pointerLockElement===null),'Pause releases actual browser pointer lock');
  const slider=(await state()).aa_mouse.slider;
  await page.mouse.click(slider[0]+45,slider[1]);
  await wait(()=>window.firstSortieState.aa_mouse.sensitivity>1.1);
  check((await state()).aa_mouse.sensitivity>1.1,'Pause slider adjusts saved AA mouse sensitivity');
  await page.keyboard.press('Escape');await page.mouse.click(640,400);
  await wait(()=>window.firstSortieState.aa_mouse.captured && window.firstSortieState.aa_mouse.armed);
  check((await state()).aa_shots===0,'Recapture click never fires the gun');
  await page.keyboard.press('m');await wait(()=>!window.firstSortieState.aa_mouse.captured);
  check(await page.evaluate(()=>document.pointerLockElement===null),'Navigation menu releases browser pointer lock');
  await page.keyboard.press('m');await page.mouse.click(640,400);
  await wait(()=>window.firstSortieState.aa_mouse.captured && window.firstSortieState.aa_mouse.armed);
  await wait(()=>window.firstSortieState.aa_defence.phase==='ACTIVE');
  check((await state()).aa_defence.wave===1 && (await state()).aa_defence.spawned===1,'Countdown produces exactly one initial Stuka');
  await wait(()=>window.firstSortieState.aa_defence.markers?.some(Boolean));
  check((await state()).aa_defence.markers.some(Boolean),'Enemy name marker remains visible through AA camera');
  await page.mouse.down();await wait(()=>window.firstSortieState.aa_shots===1);await wait(()=>window.firstSortieState.aa_reload===0);
  check((await state()).aa_shots===1,'Holding heavy trigger does not repeat after reload');
  await page.mouse.up();await delay(300);await page.mouse.down();await wait(()=>window.firstSortieState.aa_shots===2);await page.mouse.up();
  check((await state()).aa_shots===2 && (await state()).aa_heavy_count===12 && (await state()).aa_light_count===6,'Manual browser heavy press fires once; all batteries contain four heavy and two Bofors');
  const world=(await state()).world_id;
  await page.screenshot({path:'/tmp/dive-defence-browser.png'});
  await page.keyboard.press('e');await wait(()=>window.firstSortieState.ground_mode==='walking');
  check((await state()).world_id===world && (await state()).aa_defence.wave===1,'Dismount keeps live battle and world');
  await page.keyboard.press('r');await wait(previous=>window.firstSortieState.world_id!==previous && window.firstSortieState.aa_defence.phase==='WAIT_MOUNT',world);
  check((await state()).aa_defence.spawned===0 && (await state()).aa_defence.player_hp===100 && (await state()).aa_healthy,'Browser retry resets enemy/wave, health and interaction state');
  const fresh=await state();
  const near=fresh.gun_positions.reduce((best,p,i)=>Math.hypot(p[0]-fresh.ground_position[0],p[2]-fresh.ground_position[2])<Math.hypot(fresh.gun_positions[best][0]-fresh.ground_position[0],fresh.gun_positions[best][2]-fresh.ground_position[2])?i:best,0);
  const light=Math.floor(near/6)*6+4;
  const offset=fresh.ground_position.map((v,i)=>v-fresh.gun_positions[near][i]);
  const offsetLength=Math.hypot(offset[0],offset[2]);
  const target=fresh.ground_position.map((v,i)=>fresh.gun_positions[light][i]+offset[i]*3.5/Math.max(offsetLength,1));
  await walk(target);
  await page.keyboard.press('e');await wait(()=>window.firstSortieState.ground_mode==='gun' && window.firstSortieState.ground_prompt.includes('Bofors'));
  const beforeLight=(await state()).aa_mouse;
  await page.mouse.move(720,350,{steps:8});
  await wait(previous=>Math.abs(window.firstSortieState.aa_mouse.yaw-previous.yaw)>.04,beforeLight);
  check((await state()).aa_mouse.captured && Math.abs((await state()).aa_mouse.pitch-beforeLight.pitch)>.02,'Bofors also uses captured relative mouse on both axes');
  await page.mouse.down();await wait(()=>window.firstSortieState.aa_shots>=5);await page.mouse.up();
  check((await state()).aa_shots>=5 && !(await state()).ground_prompt.includes('CLIP'),'Bofors LMB continues beyond four rounds with no clip handling or ammunition limits');
  await page.keyboard.press('e');await wait(()=>window.firstSortieState.ground_mode==='walking');
  check(!(await state()).aa_mouse.captured && await page.evaluate(()=>document.pointerLockElement===null),'Bofors dismount releases actual pointer lock');
  check(errors.length===0,'No browser script/shader/resource errors');
  console.log(`DIVE DEFENCE WEB RESULT: ${checks}/${checks} passed`);
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1});
